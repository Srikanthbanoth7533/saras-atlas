"""
SARAS ATLAS — Scenario Simulation & Governance Domain Models.
Scenarios, Ephemeral Parameters, Simulation Output Runs, Optimization Recommendations, and Cryptographic Approvals.
"""

from typing import List, Optional, Any, Dict
from sqlalchemy import String, Numeric, Integer, Boolean, ForeignKey, JSON, Text, UniqueConstraint, Index
from sqlalchemy.orm import Mapped, mapped_column, relationship

from src.database.base import Base, TimestampMixin, generate_uuid


class Scenario(Base, TimestampMixin):
    """Scenario branch for evaluating counterfactual shocks and mitigations."""
    __tablename__ = "scenarios"

    id: Mapped[str] = mapped_column(String(36), primary_key=True, default=generate_uuid)
    org_id: Mapped[str] = mapped_column(String(36), ForeignKey("organizations.id", ondelete="CASCADE"), nullable=False, index=True)
    name: Mapped[str] = mapped_column(String(255), nullable=False)  # e.g. 'Disruption: Trans-Pacific Delay + Surcharge'
    description: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    scenario_type: Mapped[str] = mapped_column(String(32), default="DISRUPTION", nullable=False)  # BASELINE, DISRUPTION, MITIGATION_OPTIMAL
    is_active: Mapped[bool] = mapped_column(Boolean, default=True, nullable=False)
    created_by_user_id: Mapped[Optional[str]] = mapped_column(String(36), nullable=True)

    # Relationships
    organization: Mapped["Organization"] = relationship("Organization", back_populates="scenarios")
    params: Mapped[List["ScenarioParam"]] = relationship("ScenarioParam", back_populates="scenario", cascade="all, delete-orphan")
    simulation_runs: Mapped[List["SimulationRun"]] = relationship("SimulationRun", back_populates="scenario", cascade="all, delete-orphan")


class ScenarioParam(Base, TimestampMixin):
    """Parametric shock levers applied to a scenario branch."""
    __tablename__ = "scenario_params"
    __table_args__ = (
        UniqueConstraint("scenario_id", "param_key", "target_entity_id", name="uq_scenario_param"),
    )

    id: Mapped[str] = mapped_column(String(36), primary_key=True, default=generate_uuid)
    scenario_id: Mapped[str] = mapped_column(String(36), ForeignKey("scenarios.id", ondelete="CASCADE"), nullable=False, index=True)
    param_key: Mapped[str] = mapped_column(String(64), nullable=False)  # e.g. SUPPLIER_DELAY_DAYS, FREIGHT_SURCHARGE_PCT, DEMAND_SURGE_PCT
    param_value: Mapped[float] = mapped_column(Numeric(12, 4), nullable=False)  # e.g. 21.0000, 0.2800, 1.4500
    target_entity_type: Mapped[Optional[str]] = mapped_column(String(32), nullable=True)  # PURCHASE_ORDER, CARRIER_LANE, SKU
    target_entity_id: Mapped[Optional[str]] = mapped_column(String(64), nullable=True)  # e.g. PO-9012, APEX-JKT-BLK

    # Relationships
    scenario: Mapped["Scenario"] = relationship("Scenario", back_populates="params")


class SimulationRun(Base, TimestampMixin):
    """Persisted output metrics and financial statements from a simulation execution."""
    __tablename__ = "simulation_runs"

    id: Mapped[str] = mapped_column(String(36), primary_key=True, default=generate_uuid)
    scenario_id: Mapped[str] = mapped_column(String(36), ForeignKey("scenarios.id", ondelete="CASCADE"), nullable=False, index=True)
    execution_duration_ms: Mapped[int] = mapped_column(Integer, nullable=False)
    horizon_days: Mapped[int] = mapped_column(Integer, default=90, nullable=False)
    
    # Financial Statement Output
    total_projected_revenue: Mapped[float] = mapped_column(Numeric(14, 2), nullable=False)
    total_projected_cogs: Mapped[float] = mapped_column(Numeric(14, 2), nullable=False)
    total_projected_freight: Mapped[float] = mapped_column(Numeric(14, 2), nullable=False)
    total_projected_contribution_margin: Mapped[float] = mapped_column(Numeric(14, 2), nullable=False)
    projected_margin_rate: Mapped[float] = mapped_column(Numeric(6, 4), nullable=False)
    
    # Operational Risk Metrics
    total_lost_revenue_stockouts: Mapped[float] = mapped_column(Numeric(14, 2), default=0.00, nullable=False)
    stockout_days_count: Mapped[int] = mapped_column(Integer, default=0, nullable=False)
    working_capital_required: Mapped[float] = mapped_column(Numeric(14, 2), default=0.00, nullable=False)
    
    # Serialized Timeseries Payload (Daily Balances & Cash)
    timeseries_payload: Mapped[Optional[Dict[str, Any]]] = mapped_column(JSON, nullable=True)

    # Relationships
    scenario: Mapped["Scenario"] = relationship("Scenario", back_populates="simulation_runs")
    recommendations: Mapped[List["Recommendation"]] = relationship("Recommendation", back_populates="simulation_run", cascade="all, delete-orphan")


class Recommendation(Base, TimestampMixin):
    """Prescriptive mitigation plan generated by the Google OR-Tools MILP solver."""
    __tablename__ = "recommendations"

    id: Mapped[str] = mapped_column(String(36), primary_key=True, default=generate_uuid)
    simulation_run_id: Mapped[str] = mapped_column(String(36), ForeignKey("simulation_runs.id", ondelete="CASCADE"), nullable=False, index=True)
    recommendation_type: Mapped[str] = mapped_column(String(64), nullable=False)  # MILP_GLOBAL_OPTIMAL, EMERGENCY_AIR_FREIGHT, INTER_NODE_TRANSFER
    action_payload: Mapped[Dict[str, Any]] = mapped_column(JSON, nullable=False)  # Allocation arrays (units, sources, costs)
    estimated_margin_saved: Mapped[float] = mapped_column(Numeric(12, 2), nullable=False)
    estimated_capital_required: Mapped[float] = mapped_column(Numeric(12, 2), nullable=False)
    status: Mapped[str] = mapped_column(String(32), default="PENDING_APPROVAL", nullable=False)  # PENDING_APPROVAL, APPROVED, REJECTED

    # Relationships
    simulation_run: Mapped["SimulationRun"] = relationship("SimulationRun", back_populates="recommendations")
    approvals: Mapped[List["ApprovalRecord"]] = relationship("ApprovalRecord", back_populates="recommendation", cascade="all, delete-orphan")


class ApprovalRecord(Base, TimestampMixin):
    """Immutable audit record and digital signature for human-in-the-loop governance."""
    __tablename__ = "approval_records"

    id: Mapped[str] = mapped_column(String(36), primary_key=True, default=generate_uuid)
    recommendation_id: Mapped[Optional[str]] = mapped_column(String(36), ForeignKey("recommendations.id", ondelete="CASCADE"), nullable=True, index=True)
    approver_user_id: Mapped[str] = mapped_column(String(36), nullable=False)
    role: Mapped[str] = mapped_column(String(32), nullable=False)  # COO, CFO, FOUNDER
    decision: Mapped[str] = mapped_column(String(32), nullable=False)  # APPROVED, REJECTED
    comments: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    digital_signature_hash: Mapped[str] = mapped_column(String(128), nullable=False)  # SHA-256 fingerprint

    # Relationships
    recommendation: Mapped["Recommendation"] = relationship("Recommendation", back_populates="approvals")
